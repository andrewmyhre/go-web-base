import { BASE_CSS } from './base';
import type { StyleDef, StyleTokens } from './types';

/** Tokens a style may leave out; these values (a dark scrim in both themes) are used instead. */
export const FALLBACK_TOKENS: Record<string, [string, string]> = {
	'--wb-overlay': ['rgba(15, 23, 42, 0.55)', 'rgba(0, 0, 0, 0.65)']
};

/** Tokens every style must give in both themes. */
export const REQUIRED_TOKENS = [
	'--wb-font-heading',
	'--wb-font-body',
	'--wb-bg',
	'--wb-surface',
	'--wb-border',
	'--wb-border-strong',
	'--wb-text',
	'--wb-muted',
	'--wb-accent',
	'--wb-accent-text',
	'--wb-radius',
	'--wb-success',
	'--wb-success-bg',
	'--wb-warning',
	'--wb-warning-bg',
	'--wb-danger',
	'--wb-danger-bg',
	'--wb-danger-text',
	'--wb-info',
	'--wb-info-bg',
	'--wb-neutral-bg',
	'--wb-focus'
] as const;

/** The Google Fonts stylesheet URL for a style's families. */
export function fontHref(s: Pick<StyleDef, 'fonts'>): string {
	const fam = s.fonts.map((f) => 'family=' + f.trim().replace(/ /g, '+')).join('&');
	return `https://fonts.googleapis.com/css2?${fam}&display=swap`;
}

/** Is this a valid css2 family spec, e.g. "Fraunces:opsz,wght@9..144,400;9..144,700"? */
export function fontSpecValid(spec: string): boolean {
	const m = /^([A-Z][A-Za-z0-9]*(?: [A-Z0-9][A-Za-z0-9]*)*)(?::([a-zA-Z,]+)@([0-9.,;]+))?$/.exec(spec);
	if (!m) return false;
	if (!m[2]) return true;
	const axes = m[2].split(',');
	if (axes.some((a) => !/^(ital|opsz|slnt|wdth|wght|[A-Z]{4})$/.test(a)) || new Set(axes).size !== axes.length) return false;
	return m[3].split(';').every((t) => {
		const v = t.split(',');
		return v.length === axes.length && v.every((x) => /^\d+(\.\d+)?(\.\.\d+(\.\d+)?)?$/.test(x));
	});
}

/** Both themes' value of every token, fallbacks filled in, in a stable order. */
export function resolveTokens(s: Pick<StyleDef, 'light' | 'dark'>): Record<string, [string, string]> {
	const out: Record<string, [string, string]> = {};
	const keys = new Set<string>([...REQUIRED_TOKENS, ...Object.keys(FALLBACK_TOKENS), ...Object.keys(s.light), ...Object.keys(s.dark)]);
	for (const k of keys) {
		const fb = FALLBACK_TOKENS[k];
		const l = s.light[k as keyof StyleTokens] ?? s.dark[k as keyof StyleTokens] ?? fb?.[0];
		const d = s.dark[k as keyof StyleTokens] ?? s.light[k as keyof StyleTokens] ?? fb?.[1];
		if (l !== undefined && d !== undefined) out[k] = [l, d];
	}
	return out;
}

/** Problems with a style's extra css; empty means it is safe to ship. */
export function cssErrors(css: string): string[] {
	const errors: string[] = [];
	const src = css.replace(/\/\*[\s\S]*?\*\//g, '');
	if (/@import/i.test(src)) errors.push('@import is not allowed (fonts come from fonts)');
	if (/@font-face/i.test(src)) errors.push('@font-face is not allowed (use Google Fonts through fonts)');
	if (/url\(/i.test(src)) errors.push('url() is not allowed (no images, no external files)');
	if (/https?:\/\//i.test(src)) errors.push('external URLs are not allowed');
	let depth = 0;
	for (const ch of src) {
		if (ch === '{') depth++;
		if (ch === '}') depth--;
		if (depth < 0) break;
	}
	if (depth !== 0) errors.push('unbalanced braces');
	return errors;
}

/**
 * The whole stylesheet for a style: the font import, the tokens on :root as
 * light-dark(light, dark), the shared component rules, then the style's own.
 * This is the text of styles/<slug>.css in the package.
 */
export function styleCss(s: StyleDef): string {
	const tokens = Object.entries(resolveTokens(s))
		.map(([k, [l, d]]) => `\t${k}: ${l === d ? l : `light-dark(${l}, ${d})`};`)
		.join('\n');
	return `/* ${s.name}: ${s.description}\n   Generated by pnpm run generate:styles from src/lib/styles/data/${s.slug}.ts. Do not edit. */\n@import url('${fontHref(s)}');\n\n:root {\n${tokens}\n}\n\n${BASE_CSS}${s.css ? `\n/* ${s.name} */${s.css}` : ''}`;
}
